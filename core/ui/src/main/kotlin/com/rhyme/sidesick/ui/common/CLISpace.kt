package com.rhyme.sidesick.ui.common

/**
 * CLI 尺寸大小
 *
 * Values are in character/column units, not pixel.
 */
object CLISpace {
    const val xs = 1 // extra-small: 1 column
    const val sm = 2 // small: 2 column
    const val md = 4 // medium: 4 column
    const val lg = 8 // large: 8 column
    const val xl = 16 // extra large: 16 column

    // Line Space (number of empty lines between sections)
    const val spaceLine = 1 // one empty lines between sections
    const val spaceSection = 2 // two empty lines between major sections
}